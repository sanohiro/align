static uint64_t now_ns(void) {
    struct timespec t;
    if (clock_gettime(CLOCK_MONOTONIC, &t) != 0) abort();
    return (uint64_t)t.tv_sec * UINT64_C(1000000000) + (uint64_t)t.tv_nsec;
}
static uint64_t run(int group, size_t rounds, uint64_t *calls, uint64_t *invalid) {
    uint64_t checksum = 0;
    *calls = *invalid = 0;
    for (size_t r = 0; r < rounds; ++r) {
        for (size_t i = 0; i < sizeof goldens / sizeof *goldens; ++i) {
            const Golden *g = &goldens[i];
            if (g->group != group) continue;
            int64_t value = 123;
            int status = align_rt_str_parse_i64((const unsigned char *)g->text, g->len, &value);
            if (status != g->status || value != g->value) {
                fprintf(stderr, "golden %zu: status %d value %" PRId64 "\n", i, status, value);
                exit(1);
            }
            ++*calls;
            *invalid += status != 0;
            checksum += (uint64_t)value + (uint64_t)status;
        }
    }
    return checksum;
}
int main(int argc, char **argv) {
    if (argc != 2 || argv[1][0] < '0' || argv[1][0] > '6' || argv[1][1] != 0) return 2;
    int group = argv[1][0] - '0';
    uint64_t per_calls = 0, per_invalid = 0, per_sum = 0;
    for (size_t i = 0; i < sizeof goldens / sizeof *goldens; ++i) {
        const Golden *g = &goldens[i];
        if (g->group == group) {
            ++per_calls; per_invalid += g->status != 0;
            per_sum += (uint64_t)g->value + (uint64_t)g->status;
        }
    }
    if (!per_calls) return 3;
    uint64_t calls, invalid;
    uint64_t start = now_ns();
    do { (void)run(group, 1000, &calls, &invalid); } while (now_ns() - start < UINT64_C(50000000));
    size_t rounds = (size_t)(UINT64_C(1000000) / per_calls);
    puts("group,trial,calls,invalid_count,checksum,ns_per_call");
    for (int trial = 0; trial < 7; ++trial) {
        start = now_ns();
        uint64_t checksum = run(group, rounds, &calls, &invalid);
        uint64_t elapsed = now_ns() - start;
        if (calls != per_calls * rounds || invalid != per_invalid * rounds || checksum != per_sum * rounds) return 4;
        printf("%d,%d,%" PRIu64 ",%" PRIu64 ",%" PRIu64 ",%.3f\n", group, trial, calls, invalid, checksum, (double)elapsed / (double)calls);
    }
    return 0;
}
