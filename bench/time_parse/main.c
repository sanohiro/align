static void require(int ok, const char *message) {
    if (!ok) { fprintf(stderr, "%s\n", message); exit(2); }
}
static uint64_t now(void) {
    struct timespec t;
    require(clock_gettime(CLOCK_MONOTONIC, &t) == 0, "clock");
    return (uint64_t)t.tv_sec * UINT64_C(1000000000) + (uint64_t)t.tv_nsec;
}
int main(int argc, char **argv) {
    require(argc == 3 && strlen(argv[1]) == 1 && strlen(argv[2]) == 1 &&
        argv[1][0] >= '0' && argv[1][0] <= '4' && argv[2][0] >= '0' && argv[2][0] <= '3',
        "usage: probe kind[0..4] group[0..3]");
    int kind = argv[1][0] - '0', group = argv[2][0] - '0';
    const Golden *cases[32]; size_t lengths[32], count = 0;
    uint64_t expected_sum = 0, expected_invalid = 0;
    for (size_t i = 0; i < sizeof(goldens)/sizeof(goldens[0]); ++i) {
        if (goldens[i].kind != kind || goldens[i].group != group) continue;
        require(count < 32, "case capacity");
        cases[count] = &goldens[i]; lengths[count] = strlen(goldens[i].text);
        expected_sum += (uint64_t)goldens[i].value;
        expected_invalid += goldens[i].status != 0; count++;
    }
    require(count > 0, "nonempty group");
    uint64_t warm = now();
    do {
        for (size_t i = 0; i < count; ++i) {
            int64_t value = 99;
            int status = align_rt_time_parse(&value,(const unsigned char *)cases[i]->text,(int64_t)lengths[i],kind);
            require(status == cases[i]->status && value == cases[i]->value,"golden status/value");
        }
    } while (now()-warm < UINT64_C(50000000));
    puts("kind,group,trial,calls,invalid_count,checksum,ns_per_call");
    const uint64_t repeats = UINT64_C(1000000)/count;
    for (int trial = 0; trial < 7; ++trial) {
        uint64_t calls=0, invalid=0, sum=0, started=now();
        for (uint64_t repeat=0; repeat<repeats; ++repeat) {
            for (size_t i=0; i<count; ++i) {
                int64_t value=99;
                int status=align_rt_time_parse(&value,(const unsigned char *)cases[i]->text,(int64_t)lengths[i],kind);
                require(status==cases[i]->status && value==cases[i]->value,"timed status/value");
                calls++; invalid+=status!=0; sum+=(uint64_t)value;
            }
        }
        uint64_t elapsed=now()-started;
        require(calls==repeats*count && invalid==repeats*expected_invalid && sum==repeats*expected_sum,"observed work");
        printf("%d,%d,%d,%llu,%llu,%llu,%.3f\n",kind,group,trial,
            (unsigned long long)calls,(unsigned long long)invalid,(unsigned long long)sum,(double)elapsed/calls);
    }
}
