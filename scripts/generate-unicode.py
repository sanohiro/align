#!/usr/bin/env python3
"""Reproduce Unicode 16 NFC tables from checked, offline official UCD inputs."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'crates/align_runtime/data/unicode-16.0.0'
OUTPUT = ROOT / 'crates/align_runtime/src/unicode_data.rs'
HASHES = {
    'UnicodeData.txt': 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f',
    'DerivedNormalizationProps.txt': '4d4c03892dea9146d674b686e495df2d55a28d071ac474041d73518f887abddc',
    'NormalizationTest.txt': 'd811971453e7075e1ad56fb1b301eece5aa80757b81f6156e74a1bfb3ae5ceb1',
    'LICENSE.txt': 'e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96',
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def scalar(value):
    require(0 <= value <= 0x10ffff and not 0xd800 <= value <= 0xdfff, 'invalid scalar')
    return "'\\u{%x}'" % value


def generate():
    for name, expected in HASHES.items():
        require(hashlib.sha256((DATA / name).read_bytes()).hexdigest() == expected, name)
    combining = {}
    mappings = {}
    for line in (DATA / 'UnicodeData.txt').read_text(encoding='utf-8').splitlines():
        fields = line.split(';')
        value = int(fields[0], 16)
        if int(fields[3]):
            combining[value] = int(fields[3])
        if fields[5] and not fields[5].startswith('<'):
            mappings[value] = tuple(int(part, 16) for part in fields[5].split())
    excluded = set()
    for line in (DATA / 'DerivedNormalizationProps.txt').read_text(encoding='utf-8').splitlines():
        fields = line.split('#', 1)[0].strip().split(';')
        if len(fields) < 2 or fields[1].strip() != 'Full_Composition_Exclusion':
            continue
        bounds = fields[0].strip().split('..')
        excluded.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))

    def expand(value, path=()):
        require(value not in path, 'cyclic decomposition')
        return tuple(part for child in mappings.get(value, (value,))
                     for part in (expand(child, path + (value,)) if value in mappings else (child,)))

    decompositions = [(value, expand(value)) for value in sorted(mappings)]
    pairs = sorted((parts[0], parts[1], value) for value, parts in mappings.items()
                   if len(parts) == 2 and value not in excluded)
    require(len({(a, b) for a, b, _ in pairs}) == len(pairs), 'duplicate pair')
    require((len(combining), len(mappings), len(excluded), len(pairs)) == (934, 2081, 1120, 961), 'table inventory')
    require(max(len(parts) for _, parts in decompositions) == 4, 'decomposition extent')
    lines = [
        '// Generated by scripts/generate-unicode.py; do not edit.',
        '// Unicode 16.0.0. See ../data/unicode-16.0.0/README.md and LICENSE.txt.',
        '// Rust source bytes participate in the runtime artifact identity.',
        '#![allow(clippy::unreadable_literal)]',
        '#[cfg(test)]',
        'pub(super) const VERSION: &str = "16.0.0";',
        '#[rustfmt::skip]',
        'pub(super) static CCC: &[(char, u8)] = &[',
    ]
    lines += [f'    ({scalar(value)}, {cls}),' for value, cls in sorted(combining.items())]
    lines += ['];', '#[rustfmt::skip]', 'pub(super) static DECOMPOSITION: &[(char, &[char])] = &[']
    lines += [f'    ({scalar(value)}, &[{", ".join(map(scalar, parts))}]),' for value, parts in decompositions]
    lines += ['];', '#[rustfmt::skip]', 'pub(super) static COMPOSITION: &[(char, char, char)] = &[']
    lines += [f'    ({scalar(a)}, {scalar(b)}, {scalar(value)}),' for a, b, value in pairs]
    return '\n'.join(lines + ['];', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        require(OUTPUT.read_text(encoding='utf-8') == result, 'Unicode tables differ; regenerate explicitly')
        print('Unicode 16.0.0: input hashes and exact generated tables verified')
    else:
        OUTPUT.write_text(result, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
